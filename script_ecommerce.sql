CREATE TABLE CLIENT (
    ID_CLIENT BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(60) NOT NULL,
    EMAIL VARCHAR(120),
    CPF VARCHAR(11) NOT NULL,
    REGISTRATION_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UQ_CPF_CLIENT UNIQUE (CPF)
);

CREATE TABLE ORDERS (
    ID_ORDER BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_CLIENT BIGINT NOT NULL,
    ORDER_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STATUS VARCHAR(30) NOT NULL,
    TOTAL_AMOUNT DECIMAL(10, 2) NOT NULL,
    CONSTRAINT FK_ORDERS_CLIENT FOREIGN KEY (ID_CLIENT) REFERENCES CLIENT(ID_CLIENT)
);

CREATE TABLE PRODUCT (
    ID_PRODUCT BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(60) NOT NULL,
    PRICE DECIMAL(10, 2) NOT NULL,
    AMOUNT INT NOT NULL,
    CONSTRAINT UQ_NAME_PRODUCT UNIQUE (NAME)
);

CREATE TABLE PRODUCT_ORDERS (
    ID_PRODUCT BIGINT NOT NULL,
    ID_ORDERS BIGINT NOT NULL,
    QUANTITY INT NOT NULL DEFAULT 1,
    UNIT_PRICE DECIMAL(10, 2) NOT NULL,
    DISCOUNT DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    CONSTRAINT PK_ORDER_ITEMS PRIMARY KEY (ID_PRODUCT, ID_ORDERS),
    CONSTRAINT FK_ORDER_ITEMS_PRODUCT FOREIGN KEY (ID_PRODUCT) REFERENCES PRODUCT(ID_PRODUCT),
    CONSTRAINT FK_ORDER_ITEMS_ORDERS FOREIGN KEY (ID_ORDERS) REFERENCES ORDERS(ID_ORDERS)
);

