SELECT 
    c.NAME AS client_name,
    o.ID_ORDERS AS order_id,
    o.ORDER_DATE AS order_date,
    o.STATUS AS order_status,
    p.NAME AS product_name,
    po.QUANTITY AS quantity,
    po.UNIT_PRICE AS unit_price,
    (po.QUANTITY * po.UNIT_PRICE) - po.DISCOUNT AS item_subtotal
FROM ORDERS o
JOIN CLIENT c ON o.ID_CLIENT = c.ID_CLIENT
JOIN PRODUCT_ORDERS po ON o.ID_ORDERS = po.ID_ORDERS
JOIN PRODUCT p ON po.ID_PRODUCT = p.ID_PRODUCT
ORDER BY o.ID_ORDERS;
